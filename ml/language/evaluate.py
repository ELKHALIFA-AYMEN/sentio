"""Measure the language detector of the enrichment service.

Run from the repository root:

    uv run python ml/language/evaluate.py

Two samples:

- **simulator**: messages generated by the simulator, whose intended language is known.
  Template sentences are long and clean, so this is the easy case.
- **hand-written** (eval_set.csv): messages written for this evaluation, independently of the
  simulator templates: full sentences, short replies, sentences mixing French and English, texts
  without letters.

Each answer is counted as correct, wrong, or ``und`` (the detector abstained).
"""

import csv
import sys
import time
from collections import Counter, defaultdict
from datetime import UTC, datetime
from pathlib import Path

from sentio_enrichment import LangidDetector
from sentio_simulator import generate_conversation

EVAL_SET = Path(__file__).with_name("eval_set.csv")
SIMULATOR_MESSAGES = 2_000
START = datetime(2026, 11, 17, tzinfo=UTC)


def simulator_sample(size: int) -> list[tuple[str, str]]:
    """``size`` (text, language) pairs from conversations generated with seeds 0, 1, 2..."""
    sample: list[tuple[str, str]] = []
    seed = 0
    while len(sample) < size:
        conversation = generate_conversation(seed, START)
        sample.extend((event.text, conversation.language.value) for event in conversation.events)
        seed += 1
    return sample[:size]


def hand_written_sample() -> dict[str, list[tuple[str, str]]]:
    by_category: dict[str, list[tuple[str, str]]] = defaultdict(list)
    with EVAL_SET.open(encoding="utf-8", newline="") as file:
        for row in csv.DictReader(file):
            by_category[row["category"]].append((row["text"], row["expected"]))
    return by_category


def score(
    detector: LangidDetector, sample: list[tuple[str, str]]
) -> tuple[Counter[str], list[str]]:
    outcomes: Counter[str] = Counter()
    mistakes: list[str] = []
    for text, expected in sample:
        found = detector.detect(text).language.value
        if found == expected:
            outcomes["correct"] += 1
        elif found == "und":
            outcomes["und"] += 1
            mistakes.append(f"  und   {text!r} (expected {expected})")
        else:
            outcomes["wrong"] += 1
            mistakes.append(f"  wrong {text!r}: {found} (expected {expected})")
    return outcomes, mistakes


def row(name: str, size: int, outcomes: Counter[str]) -> str:
    def share(key: str) -> str:
        return f"{outcomes[key]} ({outcomes[key] / size:.0%})"

    return f"| {name} | {size} | {share('correct')} | {share('wrong')} | {share('und')} |"


def main() -> int:
    started = time.perf_counter()
    detector = LangidDetector()
    load_seconds = time.perf_counter() - started

    simulator = simulator_sample(SIMULATOR_MESSAGES)
    started = time.perf_counter()
    for text, _ in simulator:
        detector.detect(text)
    per_second = len(simulator) / (time.perf_counter() - started)

    lines = [
        f"Detector: {detector.version}, model loaded in {load_seconds:.2f} s, "
        f"{per_second:,.0f} messages/s on one core.",
        "",
        "| Sample | Messages | Correct | Wrong | `und` |",
        "|---|---|---|---|---|",
    ]
    all_mistakes: list[str] = []
    outcomes, mistakes = score(detector, simulator)
    distinct = len({text for text, _ in simulator})
    lines.append(row(f"simulator ({distinct} distinct texts)", len(simulator), outcomes))
    all_mistakes += mistakes
    for category, sample in hand_written_sample().items():
        outcomes, mistakes = score(detector, sample)
        lines.append(row(f"hand-written: {category}", len(sample), outcomes))
        all_mistakes += mistakes

    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    print("\n".join(lines))  # noqa: T201 - a command-line report
    print("\nNot correct:\n" + "\n".join(all_mistakes or ["  (none)"]))  # noqa: T201
    return 0


if __name__ == "__main__":
    sys.exit(main())
